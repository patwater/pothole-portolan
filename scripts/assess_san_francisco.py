#!/usr/bin/env python3
"""Assess behavior for San Francisco: re-derive every claim from its archive by a second path.

Independence, stated honestly: the same author wrote Extract and Assess, so independence comes
from method, not from a second person. Extract read HTML with regex tag-stripping and PDFs with
`pdftotext -layout`, anchored on one set of phrases. Assess reads HTML with html.parser and PDFs
with `pdftotext -raw` (which emits tables column by column), and uses different anchor phrases.

Outcomes per claim:
  re-derived  -> value, and period where checkable, reproduced by the second path
  partial     -> the stated figure is found but does not reproduce exactly from its parts
  failed      -> cannot be re-derived; the claim is demoted to `speculative`
Confidence: `supported` only if re-derived, the mechanical checks pass, and the source leaves the
claim's meaning clear. A meaning that the source leaves open keeps `provisional` (JUDGMENT below).

Usage: python3 -I scripts/assess_san_francisco.py [--root DIR] [--dry-run]
"""
import argparse
import hashlib
import re
import subprocess
import sys
from decimal import Decimal
from html.parser import HTMLParser
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate  # noqa: E402

SLUG = "san-francisco"
HEADER = (
    "# Generated by scripts/extract_san_francisco.py from the archives in sources/. Do not hand-edit\n"
    "# values; re-run the script. Assess may change `confidence`, which the script preserves.\n"
)
WORDS = {"one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10}

# Claims whose figure is reproducible but whose meaning the source leaves unclear. Kept provisional.
JUDGMENT = {
    "sf-blocks-resurfaced-as-of-2025-11": "The slide gives no start year or period, so whether 9,148 is cumulative, annual or since a program start is unknown.",
    "sf-blocks-planned-as-of-2025-11": "A lower bound ('2,500+') with no planning horizon stated.",
}


class _Text(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts, self.skip = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self.skip += 1

    def handle_endtag(self, tag):
        if tag in ("script", "style") and self.skip:
            self.skip -= 1

    def handle_data(self, data):
        if not self.skip:
            self.parts.append(data)


def html_flat(path):
    p = _Text()
    p.feed(Path(path).read_bytes().decode("utf-8", "replace"))
    return re.sub(r"\s+", " ", " ".join(p.parts))


def pdf_raw(path):
    return subprocess.run(["pdftotext", "-raw", str(path), "-"], capture_output=True, text=True, check=True).stdout


def num(s):
    return int(s.replace(",", ""))


def m(text, pattern):
    return re.search(pattern, text, re.S)


# ---- independent re-derivations: each returns (status, detail) --------------------------------

def rd_release_2023(c, t):
    a = m(t, r"Pavement Condition Index rating is (\d+), meaning in “good” condition")
    y = m(t, r"covered calendar year (\d{4})")
    if m(t, r"January 8, 2024") and a and y and int(a.group(1)) == c["value"] and y.group(1) == str(c["period"]):
        return "re-derived", f"headline and body both give {a.group(1)}; body says calendar year {y.group(1)}; release dated January 8, 2024"
    return "failed", "headline value or year not reproduced"


def rd_mtc_county(c, t):
    a = m(t, r"(\d+) San Francisco County had the highest pavement quality of the region's counties in 2024")
    return ("re-derived", f"headline tile reads {a.group(1)}") if a and int(a.group(1)) == c["value"] else ("failed", "tile not reproduced")


def rd_mtc_change(c, t):
    a = m(t, r"\+(\d+) San Francisco County had the region's greatest improvement")
    w = m(t, r"San Francisco and Santa Clara counties had the biggest improvements in PCI from 2014 to 2024, gaining (\w+) and")
    if a and w and int(a.group(1)) == c["value"] == WORDS[w.group(1).lower()]:
        return "re-derived", f"tile '+{a.group(1)}' and text '{w.group(1)}' points agree"
    return "failed", "tile and text do not agree with the claim"


def rd_mtc_bay(c, t):
    a = m(t, r"(\d+) In 2024 Bay Area streets had an average PCI")
    b = m(t, r"held steady at (\d+) in 2024")
    if a and b and int(a.group(1)) == int(b.group(1)) == c["value"]:
        return "re-derived", f"tile and body both give {a.group(1)}"
    return "failed", "tile and body not reproduced"


def network_table(raw):
    """Rebuild the table from -raw output: three columns of 11 numbers, then the 11 years."""
    seg = raw.split("Annual Network Condition", 1)[1].split("December 2024 Network Condition", 1)[0]
    toks = [x for x in seg.split() if re.fullmatch(r"[\d,]+", x)]
    cols, years = toks[:33], toks[33:44]
    if [int(y) for y in years] != list(range(2014, 2025)):
        return None
    return {int(y): (num(cols[i]), num(cols[11 + i]), num(cols[22 + i])) for i, y in enumerate(years)}


def make_rd_block(idx):
    def rd(c, t):
        tab = network_table(t)
        if tab is None:
            return "failed", "could not rebuild the table by columns"
        year = int(c["period"])
        got = tab[year][idx]
        ok = got == c["value"]
        return ("re-derived", f"column-wise rebuild gives {got:,} for {year}; category identity from the slide legend colors") if ok else ("failed", f"column-wise rebuild gives {got:,}")
    return rd


def rd_resurfaced(c, t):
    a = m(t, r"\n([\d,]+)\nBlocks Resurfaced\n")
    return ("re-derived", f"{a.group(1)} beside the label in the -raw text (confirmed by eye on rendered slide 5 during this run)") if a and num(a.group(1)) == c["value"] else ("failed", "not reproduced")


def rd_planned(c, t):
    a = m(t, r"\n([\d,]+)\+\nBlocks Planned")
    return ("re-derived", f"{a.group(1)}+ beside the label in the -raw text (confirmed by eye on rendered slide 5 during this run)") if a and num(a.group(1)) == c["value"] else ("failed", "not reproduced")


def rd_cost(c, t):
    top = m(t, r"\$([\d,]+)\.00")
    parts = re.findall(r"\$([\d,]+) – (?:Staff Time|4 Curb Ramps|Localized Base Repair|Paving|Other)", t)
    if top and len(parts) == 5 and num(top.group(1)) == c["value"] == sum(num(x) for x in parts):
        return "re-derived", f"headline ${top.group(1)} equals the five category amounts, which sum to ${sum(num(x) for x in parts):,}"
    return "failed", "headline and category amounts do not agree"


def awards(raw):
    rows = re.findall(r"\$ ([\d.]+) M (\d{1,2}/\d{1,2}/\d{4}) (\d+)", raw)
    tot = m(raw, r"TOTAL \$ ([\d.]+) M (\d+)")
    return rows, tot


def rd_awards_amount(c, t):
    rows, tot = awards(t)
    if not tot or Decimal(tot.group(1)) != Decimal(str(c["value"])):
        return "failed", "TOTAL row not reproduced"
    s = sum(Decimal(r[0]) for r in rows)
    if s == Decimal(tot.group(1)):
        return "re-derived", f"{len(rows)} rows sum to {s}"
    return "partial", f"TOTAL row reads ${tot.group(1)}M, but the {len(rows)} rounded rows sum to ${s}M"


def rd_awards_blocks(c, t):
    rows, tot = awards(t)
    s = sum(int(r[2]) for r in rows)
    if tot and int(tot.group(2)) == c["value"] == s:
        return "re-derived", f"{len(rows)} rows sum to {s}, equal to the TOTAL row"
    return "failed", f"rows sum to {s}"


def rd_72(c, t):
    a = m(t, r"target of (\d+) hours")
    b = m(t, r"goal of responding to service requests about potholes within (\d+) hours")
    if a and b and int(a.group(1)) == int(b.group(1)) == c["value"]:
        return "re-derived", "both the measure description and the method text give 72 hours"
    return "failed", "72 hours not reproduced in both places"


def rd_two(c, t):
    a = m(re.sub(r"\s+", " ", t), r"SFPW inspects each of the City's blocks and assigns a Pavement Condition Index \(PCI\) score every (\w+) years")
    n = len(re.findall(r"SFPW inspects each of the City's blocks and assigns a Pavement Condition Index \(PCI\) score every " + (a.group(1) if a else "x") + " years", re.sub(r"\s+", " ", t)))
    return ("re-derived", f"text says 'every {a.group(1)} years' ({n} occurrence(s) in the document)") if a and WORDS[a.group(1)] == c["value"] else ("failed", "not reproduced")


def rd_three(c, t):
    a = m(t, r"updated every (\w+) years")
    return ("re-derived", f"text says 'updated every {a.group(1)} years'") if a and WORDS[a.group(1)] == c["value"] else ("failed", "not reproduced")


DERIVE = {
    "sf-pci-citywide-2023": rd_release_2023,
    "sf-pci-county-2024-mtc": rd_mtc_county,
    "sf-pci-county-change-2014-2024-mtc": rd_mtc_change,
    "bay-area-pci-2024-mtc": rd_mtc_bay,
    "sf-blocks-resurfaced-as-of-2025-11": rd_resurfaced,
    "sf-blocks-planned-as-of-2025-11": rd_planned,
    "sf-avg-cost-per-paved-block-2025-11": rd_cost,
    "sf-resurfacing-awards-amount-2023-2025": rd_awards_amount,
    "sf-resurfacing-awards-blocks-2023-2025": rd_awards_blocks,
    "sf-pothole-response-target-72h": rd_72,
    "sf-publicworks-pci-interval-years": rd_two,
    "mtc-pavement-survey-update-interval-years": rd_three,
}
for _year in (2014, 2024):
    for _i, _slug in enumerate(("very-poor", "poor-atrisk", "good-excellent")):
        DERIVE[f"sf-blocks-{_slug}-{_year}"] = make_rd_block(_i)


# ---- mechanical checks -----------------------------------------------------------------------

def mechanical(root, c, sources):
    problems = []
    path = Path(root) / c["archive"]
    if not path.is_file():
        return [f"archive {c['archive']} missing"]
    if hashlib.sha256(path.read_bytes()).hexdigest() != Path(c["archive"]).stem:
        problems.append("archive hash does not match its name")
    src = next((s for s in sources if s.get("archive") == c["archive"] and s.get("status") == "fetched"), None)
    if src is None:
        problems.append("archive is not a fetched source in sources.yaml")
    elif src["url"] != c["source_url"]:
        problems.append("source_url differs from the source inventory URL")
    elif src["retrieved"] != c["retrieved"]:
        problems.append("retrieved date differs from the source inventory")
    v, st = c["value"], c["statement"]
    shown = {f"{v:,}", str(v)} if isinstance(v, int) else {str(v)}
    words = {w for w, n in WORDS.items() if n == v}
    if not any(x in st for x in shown) and not any(w in st.lower() for w in words):
        problems.append("value does not appear in the statement")
    if re.fullmatch(r"\d{4}(-\d{4})?", str(c["period"])):
        for y in re.findall(r"\d{4}", str(c["period"])):
            if y not in st:
                problems.append(f"period year {y} does not appear in the statement")
    if c["kind"] == "measured_condition" and "condition_index" not in c:
        problems.append("measured_condition without condition_index")
    if c["confidence"] != "supported" and not c.get("caveats"):
        problems.append("provisional claim has no caveats")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)
    root = Path(args.root)
    sources = validate.load_yaml(root / "cities" / SLUG / "sources.yaml")
    path = root / "cities" / SLUG / "claims.yaml"
    claims = validate.load_yaml(path)
    cache, report = {}, []
    for c in claims:
        if c["id"] not in DERIVE:
            report.append((c["id"], c["confidence"], "failed", "no independent derivation defined"))
            c["confidence"] = "speculative"
            continue
        ap_ = Path(root) / c["archive"]
        if not ap_.is_file():
            report.append((c["id"], c["confidence"], "speculative", f"archive {c['archive']} does not exist, so nothing can be re-derived"))
            c["confidence"] = "speculative"
            continue
        if c["archive"] not in cache:
            cache[c["archive"]] = pdf_raw(ap_) if ap_.suffix == ".pdf" else html_flat(ap_)
        status, detail = DERIVE[c["id"]](c, cache[c["archive"]])
        problems = mechanical(root, c, sources)
        before = c["confidence"]
        if status == "failed" or problems:
            new, why = "speculative", detail + ("; " + "; ".join(problems) if problems else "")
        elif status == "partial":
            new, why = "provisional", detail
        elif c["id"] in JUDGMENT:
            new, why = "provisional", detail + ". Kept provisional: " + JUDGMENT[c["id"]]
        else:
            new, why = "supported", detail
        c["confidence"] = new
        report.append((c["id"], before, new, why))
    for cid, before, new, why in report:
        print(f"{cid:46} {before:11} -> {new:11} {why}")
    tally = {k: sum(1 for r in report if r[2] == k) for k in ("supported", "provisional", "speculative")}
    print(tally)
    if not args.dry_run:
        path.write_text(HEADER + yaml.safe_dump(claims, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8")
        errs = validate.validate_file(path, "claims.schema.json")
        for e in errs:
            print("SCHEMA", e)
        return 1 if errs else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
