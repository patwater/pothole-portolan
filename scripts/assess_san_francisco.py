def mechanical(root, c, sources):
    problems = []
    path = Path(root) / c["archive"]
    if not path.is_file():
        return [f"archive {c['archive']} missing"]
    if hashlib.sha256(path.read_bytes()).hexdigest() != Path(c["archive"]).stem:
        problems.append("archive hash does not match its name")
    src = next((s for s in sources if s.get("archive") == c["archive"] and s.get("status") == "fetched"), None)
    if src is None:
        problems.append("archive is not a fetched source in sources.yaml")
    elif src["url"] != c["source_url"]:
        problems.append("source_url differs from the source inventory URL")
    elif src["retrieved"] != c["retrieved"]:
        problems.append("retrieved date differs from the source inventory")
    v, st = c["value"], c["statement"]
    shown = {f"{v:,}", str(v)} if isinstance(v, int) else {str(v)}
    words = {w for w, n in WORDS.items() if n == v}
    if not any(x in st for x in shown) and not any(w in st.lower() for w in words):
        problems.append("value does not appear in the statement")
    if re.fullmatch(r"\d{4}(-\d{4})?", str(c["period"])):
        for y in re.findall(r"\d{4}", str(c["period"])):
            if y not in st:
                problems.append(f"period year {y} does not appear in the statement")
    if c["kind"] == "measured_condition" and "condition_index" not in c:
        problems.append("measured_condition without condition_index")
    if c["confidence"] != "supported" and not c.get("caveats"):
        problems.append("provisional claim has no caveats")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)
    root = Path(args.root)
    sources = validate.load_yaml(root / "cities" / SLUG / "sources.yaml")
    CTX["root"], CTX["sources"] = root, {s["id"]: s for s in sources}
    path = root / "cities" / SLUG / "claims.yaml"
    claims = validate.load_yaml(path)
    cache, report = {}, []
    for c in claims:
        if c["id"] not in DERIVE:
            # Never attempted is not the same as failed. Cap at provisional so an unassessed claim cannot be supported.
            before = c["confidence"]
            c["confidence"] = "provisional" if before == "supported" else before
            report.append((c["id"], before, c["confidence"], "PENDING: no independent derivation defined yet, so it has not been assessed"))
            continue
        ap_ = Path(root) / c["archive"]
        if not ap_.is_file():
            report.append((c["id"], c["confidence"], "speculative", f"archive {c['archive']} does not exist, so nothing can be re-derived"))
            c["confidence"] = "speculative"
            continue
        if c["archive"] not in cache:
            cache[c["archive"]] = pdf_raw(ap_) if ap_.suffix == ".pdf" else html_flat(ap_)
        status, detail = DERIVE[c["id"]](c, cache[c["archive"]])
        problems = mechanical(root, c, sources)
        before = c["confidence"]
        if status == "failed" or problems:
            new, why = "speculative", detail + ("; " + "; ".join(problems) if problems else "")
        elif status == "partial":
            new, why = "provisional", detail
        elif c["id"] in JUDGMENT:
            new, why = "provisional", detail + ". Kept provisional: " + JUDGMENT[c["id"]]
        else:
            new, why = "supported", detail
        c["confidence"] = new
        report.append((c["id"], before, new, why))
    for con in OPEN_CONNECTIONS:
        con.close()
    OPEN_CONNECTIONS.clear()
    for cid, before, new, why in report:
        print(f"{cid:46} {before:11} -> {new:11} {why}")
    tally = {k: sum(1 for r in report if r[2] == k) for k in ("supported", "provisional", "speculative")}
    print(tally)
    if not args.dry_run:
        path.write_text(HEADER + yaml.safe_dump(claims, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8")
        errs = validate.validate_file(path, "claims.schema.json")
        for e in errs:
            print("SCHEMA", e)
        return 1 if errs else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
