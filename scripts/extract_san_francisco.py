#!/usr/bin/env python3
"""Extract behavior for San Francisco: derive claims from archived copies in sources/.

Every claim is tied to anchor text in an archived file. If any anchor is missing, or a
cross-check fails, nothing is written and the exit status is 1. Values come only from the
archived text; nothing is typed in from memory. Re-running regenerates claims.yaml from the
archives and keeps any `confidence` that Assess has already set for an existing claim id.

Untrusted input: archives are only read as text. pdftotext is called with an argument list,
never through a shell. Run with: python3 -I scripts/extract_san_francisco.py [--root DIR]
"""
import argparse
import html
import re
import subprocess
import sys
from decimal import Decimal
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate  # noqa: E402

SLUG = "san-francisco"
HEADER = (
    "# Generated by scripts/extract_san_francisco.py from the archives in sources/. Do not hand-edit\n"
    "# values; re-run the script. Assess may change `confidence`, which the script preserves.\n"
)
NUMBER_WORDS = {"one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7,
                "eight": 8, "nine": 9, "ten": 10}
NOT_STATED = "not stated"


class ExtractError(Exception):
    pass


def html_text(raw):
    t = raw.decode("utf-8", "replace")
    t = re.sub(r"<script.*?</script>|<style.*?</style>", "", t, flags=re.S | re.I)
    t = re.sub(r"<(br|/p|/li|/h\d|/div|/tr)[^>]*>", "\n", t, flags=re.I)
    t = html.unescape(re.sub(r"<[^>]+>", " ", t))
    return re.sub(r"[ \t]+", " ", t)


def pdf_text(path):
    return subprocess.run(["pdftotext", "-layout", str(path), "-"], capture_output=True,
                          text=True, check=True).stdout


def flat(text):
    return re.sub(r"\s+", " ", text)


def find(text, pattern, what):
    m = re.search(pattern, text, re.S)
    if not m:
        raise ExtractError(f"anchor not found for {what}: /{pattern}/")
    return m


class Archive:
    def __init__(self, root, entry):
        self.entry = entry
        self.path = Path(root) / entry["archive"]
        if self.path.suffix == ".pdf":
            self.raw = pdf_text(self.path)
        else:
            self.raw = html_text(self.path.read_bytes())
        self.flat = flat(self.raw)

    def get(self, pattern, what, group=1, use_flat=True):
        return find(self.flat if use_flat else self.raw, pattern, what).group(group)

    def require(self, pattern, what):
        find(self.flat, pattern, what)


def to_number(s):
    s = s.replace(",", "")
    return int(s) if re.fullmatch(r"\d+", s) else float(s)


def build(root):
    sources = {s["id"]: s for s in validate.load_yaml(Path(root) / "cities" / SLUG / "sources.yaml")}

    def arc(source_id):
        s = sources[source_id]
        if s.get("status") != "fetched":
            raise ExtractError(f"source {source_id} is not fetched")
        return Archive(root, s)

    def base(source_id, **fields):
        s = sources[source_id]
        return dict(source_url=s["url"], retrieved=s["retrieved"], archive=s["archive"], **fields)

    claims = []

    # ---- City release (January 2024) and MTC Vital Signs: PCI ------------------------------
    city = arc("sf-city-pci-release-2024-01")
    city.require(r"January 8, 2024", "release date")
    pci_city = to_number(city.get(r"score increased to (\d+), a rating deemed “good”", "city PCI"))
    year = city.get(r"score, which covered calendar year (\d{4})", "city PCI year")
    claims.append(base(
        "sf-city-pci-release-2024-01", id="sf-pci-citywide-2023",
        statement=f"San Francisco's citywide Pavement Condition Index score, covering calendar year {year}, was {pci_city}.",
        value=pci_city, unit="PCI points", period=year, kind="measured_condition",
        method=f"Read from the city's January 8, 2024 release: 'score increased to {pci_city}' and 'which covered calendar year {year}'.",
        confidence="provisional",
        caveats="Stated in a city press release, not the MTC data. The release describes the score as rated independently and tracked by MTC. "
                "It says the 0-100 scale runs from 0 (worst) to 100 (freshly paved).",
        condition_index={"name": "Pavement Condition Index (PCI)", "scale": "0-100, 0 worst and 100 freshly paved",
                         "survey_year": int(year), "network_share_surveyed": NOT_STATED,
                         "survey_method": "not stated in this source; see the city scorecard source"}))

    mtc = arc("mtc-vital-signs-street-pavement")
    mtc.require(r"three-year moving average", "MTC averaging")
    mtc.require(r"imputed for interim years based on facility age and treatments using the MTC StreetSaver", "MTC imputation")
    mtc_method = ("PCI is a three-year moving average. Segment PCI is collected on a rolling basis and imputed for interim "
                  "years from facility age and treatments using MTC StreetSaver.")
    mtc_index = {"name": "Pavement Condition Index (PCI), MTC Vital Signs", "scale": "0 (failed) to 100 (brand-new)",
                 "survey_year": 2024, "network_share_surveyed": NOT_STATED, "survey_method": mtc_method}
    pci_sf_county = to_number(mtc.get(r"San Francisco County had the highest pavement quality of the region's counties in 2024, with an average PCI of (\d+)", "SF county PCI"))
    claims.append(base(
        "mtc-vital-signs-street-pavement", id="sf-pci-county-2024-mtc",
        statement=f"MTC Vital Signs reports San Francisco County's average PCI in 2024 as {pci_sf_county}.",
        value=pci_sf_county, unit="PCI points", period=2024, kind="measured_condition",
        method="Read from the MTC Vital Signs street pavement condition page, headline statement for 2024.",
        confidence="provisional",
        caveats="A three-year moving average, so it is not a single-year survey score. The page was last updated February 2026. "
                "Whether it is directly comparable with the city's calendar-year score is unresolved.",
        condition_index=dict(mtc_index)))
    words = mtc.get(r"San Francisco County had the region's greatest improvement in average pavement quality between 2014 and 2024, gaining (\w+) points", "SF county change")
    mtc.require(r"\+9 San Francisco County had the region's greatest improvement", "SF county change figure")
    change = NUMBER_WORDS[words.lower()]
    claims.append(base(
        "mtc-vital-signs-street-pavement", id="sf-pci-county-change-2014-2024-mtc",
        statement=f"MTC Vital Signs reports San Francisco County's average PCI rose {change} points between 2014 and 2024.",
        value=change, unit="PCI points", period="2014-2024", kind="measured_condition",
        method=f"Read from the page text 'gaining {words} points', cross-checked against the '+{change}' headline figure on the same page.",
        confidence="provisional",
        caveats="Both end points are three-year moving averages. This is a change in an index, not in the number of potholes.",
        condition_index=dict(mtc_index, survey_year="2014 and 2024")))
    pci_bay = to_number(mtc.get(r"In 2024 Bay Area streets had an average PCI of (\d+), indicating “fair”", "Bay Area PCI"))
    claims.append(base(
        "mtc-vital-signs-street-pavement", id="bay-area-pci-2024-mtc",
        statement=f"MTC Vital Signs reports the average PCI across Bay Area streets in 2024 as {pci_bay}.",
        value=pci_bay, unit="PCI points", period=2024, kind="measured_condition",
        method="Read from the MTC Vital Signs page headline for the region.",
        confidence="provisional",
        caveats="Regional context for the San Francisco figures. Not a comparison between cities.",
        condition_index=dict(mtc_index)))

    # ---- Public Works release, January 2, 2026 (the 2025 score) ---------------------------------
    rel = arc("sf-publicworks-pci-release-2026-01")
    rel.require(r"For immediate release: January 2, 2026", "2026 release date")
    rel.require(r"scale from 0-100, with zero being a pothole-riddled, crumbling street and 100 signifying a freshly paved road", "2026 release scale")
    rel.require(r"tracked by the regional Metropolitan Transportation Commission", "2026 release MTC tracking")
    pci25 = to_number(rel.get(r"maintained a Pavement Condition Index score rating of (\d+) in (\d{4})", "2025 PCI"))
    y25 = rel.get(r"maintained a Pavement Condition Index score rating of (\d+) in (\d{4})", "2025 PCI year", group=2)
    claims.append(base(
        "sf-publicworks-pci-release-2026-01", id="sf-pci-citywide-2025",
        statement=f"San Francisco's citywide Pavement Condition Index score rating for {y25}, as stated in a Public Works release dated January 2, 2026, was {pci25}.",
        value=pci25, unit="PCI points", period=y25, kind="measured_condition",
        method=f"Read from the first paragraph of the January 2, 2026 Public Works release: 'maintained a Pavement Condition Index score rating of {pci25} in {y25}'.",
        confidence="provisional",
        caveats="A city press release, not the MTC data. The release says the annual evaluation looks at the condition of each block and assigns a cumulative score, "
                "released December 31 of every year and tracked by MTC. It does not say how many blocks were surveyed or how interim years are estimated.",
        condition_index={"name": "Pavement Condition Index (PCI)", "scale": "0-100, 0 a pothole-riddled crumbling street and 100 a freshly paved road",
                         "survey_year": int(y25), "network_share_surveyed": NOT_STATED,
                         "survey_method": "annual evaluation of each block, assigned a cumulative score, tracked by MTC (per the release; no further method stated)"}))
    paved = to_number(rel.get(r"crews paved ([\d,]+) City-maintained blocks in (\d{4})", "blocks paved"))
    paved_year = rel.get(r"crews paved ([\d,]+) City-maintained blocks in (\d{4})", "blocks paved year", group=2)
    claims.append(base(
        "sf-publicworks-pci-release-2026-01", id="sf-blocks-paved-2025",
        statement=f"A Public Works release dated January 2, 2026 says crews paved {paved:,} City-maintained blocks in {paved_year}.",
        value=paved, unit="blocks", period=paved_year, kind="program_output",
        method=f"Read from the January 2, 2026 release: 'crews paved {paved:,} City-maintained blocks in {paved_year}'.",
        confidence="provisional",
        caveats="Program output, a count of blocks, not a dollar figure. The release does not say whether this counts blocks "
                "resurfaced, accepted or completed, and it does not say whether in-house and contractor work are both included beyond saying both crews do the work."))
    invest = to_number(rel.get(r"The \$(\d+) million investment over that period", "15-year investment"))
    rel.require(r"over the last 15-plus years", "investment period")
    claims.append(base(
        "sf-publicworks-pci-release-2026-01", id="sf-resurfacing-investment-15-plus-years",
        statement=f"A Public Works release dated January 2, 2026 refers to a ${invest} million investment in roadway maintenance over the last 15-plus years.",
        value=invest, unit="USD millions", period="15-plus years to 2025", kind="spending",
        method="Read from the January 2, 2026 release, which describes the city's commitment to fund roadway maintenance 'over the last 15-plus years' "
               "and then 'the $979 million investment over that period'.",
        confidence="provisional",
        caveats="The start year, the funding sources and whether the figure is nominal dollars are not stated. The release credits this spending with the rise in the score "
                "and with resurfacing more than 9,000 of nearly 13,000 blocks; that is the department's framing, not a measured effect."))
    cheap = to_number(rel.get(r"in good condition can cost as little as \$([\d,]+)", "preservation cost"))
    claims.append(base(
        "sf-publicworks-pci-release-2026-01", id="sf-preservation-cost-per-good-block-min",
        statement=f"A Public Works release dated January 2, 2026 says extending the life of a block in good condition can cost as little as ${cheap:,}.",
        value=cheap, unit="USD per block", period="as stated January 2026", kind="spending",
        method="Read from the January 2, 2026 release: 'Extending the life of a block in San Francisco that is in good condition can cost as little as $50,000'.",
        confidence="provisional",
        caveats="A floor ('as little as'), not an average. The release pairs it with a reconstruction cost for a block in very poor condition whose figure is printed as "
                "'$500,00', which is ambiguous, so that cost was deliberately not extracted. Do not compare with the average paving cost on the Commission slide without a caveat."))
    rel.require(r"Findings from the annual evaluation are released Dec\. 31 of every year", "annual release")
    claims.append(base(
        "sf-publicworks-pci-release-2026-01", id="sf-pci-annual-release-date",
        statement="Public Works says findings of the annual San Francisco PCI evaluation are released December 31 of every year.",
        value="December 31", unit="annual release date", period="annual, as stated January 2026", kind="policy",
        method="Read from the January 2, 2026 release: 'Findings from the annual evaluation are released Dec. 31 of every year'.",
        confidence="provisional",
        caveats="A third statement about survey cadence, besides the two-year inspection cycle (Prop L document) and the three-year MTC dataset update. "
                "It describes the evaluation's release, not necessarily how often each block is physically inspected."))

    # ---- Public Works Commission deck, November 13, 2025 -----------------------------------
    pw = arc("publicworks-commission-resurfacing-update-2025-11")
    pw.require(r"November 13, 2025", "deck date")
    pw.require(r"Annual Network Condition", "network condition slide")
    rows = {}
    for m in re.finditer(r"^\s*(20\d\d)\s+([\d,]+)\s+([\d,]+)\s+([\d,]+)\s*$", pw.raw, re.M):
        rows[int(m.group(1))] = tuple(int(g.replace(",", "")) for g in m.groups()[1:])
    if sorted(rows) != list(range(2014, 2025)):
        raise ExtractError(f"network condition table: expected rows 2014-2024, got {sorted(rows)}")
    pw.require(r"# of Very Poor.*# of Poor/At-Risk.*# of Good/Excellent", "table column labels")
    pw_index = lambda year: {  # noqa: E731
        "name": "PCI-based block condition categories (Public Works)",
        "scale": "PCI 0-100 grouped into Very Poor, Poor/At-Risk and Good/Excellent blocks. The deck's band edges: "
                 "Very Poor 0-25, Poor 25-50, At-Risk 50-60, Good 60-80, Excellent 80-100",
        "survey_year": year, "network_share_surveyed": NOT_STATED, "survey_method": "not stated in this source"}
    labels = [("very-poor", "very poor"), ("poor-atrisk", "poor or at-risk"), ("good-excellent", "good or excellent")]
    for year in (2024, 2014):
        for idx, (slug, label) in enumerate(labels):
            claims.append(base(
                "publicworks-commission-resurfacing-update-2025-11", id=f"sf-blocks-{slug}-{year}",
                statement=f"Public Works counted {rows[year][idx]:,} San Francisco blocks in the {label} condition category in its {year} annual network condition table.",
                value=rows[year][idx], unit="blocks", period=year, kind="measured_condition",
                method=f"Row '{year}' of the 'Annual Network Condition' slide (slide 7). Column order Very Poor, Poor/At-Risk, "
                       "Good/Excellent was confirmed against the rendered slide, whose legend colors match the bars.",
                confidence="provisional",
                caveats="The deck's band edges differ from MTC's and from the city scorecard's, so these categories must not be "
                        "merged with either. The slide does not say how many blocks were surveyed or how the grouping was made.",
                condition_index=pw_index(year)))
    # Anchor on the whole slide sequence so a page number in a footer cannot be mistaken for the figure.
    seq = r"~([\d,]+) Total Public Works Accepted Blocks ([\d,]+) Blocks Resurfaced ([\d,]+)\+ Blocks Planned"
    resurfaced = to_number(pw.get(seq, "blocks resurfaced", group=2))
    planned = to_number(pw.get(seq, "blocks planned", group=3))
    claims.append(base(
        "publicworks-commission-resurfacing-update-2025-11", id="sf-blocks-resurfaced-as-of-2025-11",
        statement=f"A Public Works Commission slide dated November 13, 2025 reports {resurfaced:,} blocks resurfaced.",
        value=resurfaced, unit="blocks", period="as of 2025-11-13", kind="program_output",
        method="Read from the 'Blocks Resurfaced and Planned' slide (slide 5).",
        confidence="provisional",
        caveats="Program output, a count of blocks, not a dollar figure. The slide gives no start year, "
                "so the period is the deck date and the count is presumably cumulative."))
    claims.append(base(
        "publicworks-commission-resurfacing-update-2025-11", id="sf-blocks-planned-as-of-2025-11",
        statement=f"A Public Works Commission slide dated November 13, 2025 reports more than {planned:,} blocks planned.",
        value=planned, unit="blocks", period="as of 2025-11-13", kind="program_output",
        method="Read from the 'Blocks Resurfaced and Planned' slide (slide 5), where the figure appears as '2,500+'.",
        confidence="provisional",
        caveats="A lower bound ('2,500+'). Program output, a count of blocks, not a dollar figure."))
    cost = to_number(pw.get(r"Average Cost for Block of Paving\s+\$([\d,]+)(?:\.00)?", "average cost per block"))
    claims.append(base(
        "publicworks-commission-resurfacing-update-2025-11", id="sf-avg-cost-per-paved-block-2025-11",
        statement=f"Public Works reports an average cost of ${cost:,} for a block of paving.",
        value=cost, unit="USD per block", period="as of 2025-11-13", kind="spending",
        method="Read from the 'Funding: Average Cost for Block of Paving' slide (slide 8).",
        confidence="provisional",
        caveats="The slide's breakdown includes staff time, four curb ramps, localized base repair and other items, "
                "so it is the cost of a full paving project block and not of filling a pothole. The year of the cost basis is not stated."))
    amounts, blocks, dates = [], [], []
    for m in re.finditer(r"\$\s*([\d.]+)\s*M\s+(\d{1,2})/(\d{1,2})/(\d{4})\s+(\d+)\s*$", pw.raw, re.M):
        amounts.append(Decimal(m.group(1)))
        dates.append((int(m.group(4)), int(m.group(2)), int(m.group(3))))
        blocks.append(int(m.group(5)))
    tot = find(pw.raw, r"TOTAL\s+\$\s*([\d.]+)\s*M\s+(\d+)", "awards total")
    row_sum, stated = sum(amounts), Decimal(tot.group(1))
    if sum(blocks) != int(tot.group(2)):
        raise ExtractError(f"award block counts sum to {sum(blocks)}, table says {tot.group(2)}")
    # Each amount is shown rounded to $0.1M, so the row sum may differ from the total by up to 0.05 per row.
    if abs(row_sum - stated) > Decimal("0.05") * len(amounts):
        raise ExtractError(f"award amounts sum to {row_sum} M, table says {stated} M, more than rounding explains")
    rounding_note = (f"The {len(amounts)} rounded project amounts sum to ${row_sum} million while the table's TOTAL row states ${stated} million, "
                     "a difference consistent with rounding each row to $0.1 million. The stated total is used.") if row_sum != stated else ""
    first, last = min(dates), max(dates)
    period = f"awards dated {first[0]}-{first[1]:02d}-{first[2]:02d} to {last[0]}-{last[1]:02d}-{last[2]:02d}"
    claims.append(base(
        "publicworks-commission-resurfacing-update-2025-11", id="sf-resurfacing-awards-amount-2023-2025",
        statement=f"Street resurfacing projects awarded by the Commission between {period[13:23]} and {period[27:]} total ${tot.group(1)} million.",
        value=float(tot.group(1)), unit="USD millions", period=period, kind="spending",
        method=f"Slide 10 table 'Projects Awarded by Commission the Last 2 Years', TOTAL row. The script also summed the {len(amounts)} project rows as a cross-check.",
        confidence="provisional",
        caveats="Award amounts, not spending to date. The slide title says 'the last 2 years' while the dates span about two and a half years. " + rounding_note))
    claims.append(base(
        "publicworks-commission-resurfacing-update-2025-11", id="sf-resurfacing-awards-blocks-2023-2025",
        statement=f"The same {len(amounts)} awarded projects cover {int(tot.group(2))} blocks.",
        value=int(tot.group(2)), unit="blocks", period=period, kind="program_output",
        method=f"Slide 10 table. The script summed the {len(blocks)} block counts and confirmed they equal the TOTAL row.",
        confidence="provisional",
        caveats="Program output, a count of blocks, not a dollar figure. One 'as needed' preservation award covers 150 blocks."))

    # ---- Pothole response target (city scorecard) -------------------------------------------
    pot = arc("sf-pothole-response-measure")
    hours = to_number(pot.get(r"goal of responding to service requests about potholes within (\d+) hours", "72-hour goal"))
    pot.require(r"number of requests responded to within three business days divided by the total number of requests received that month", "measure definition")
    claims.append(base(
        "sf-pothole-response-measure", id="sf-pothole-response-target-72h",
        statement=f"San Francisco's stated goal is to respond to pothole service requests within {hours} hours.",
        value=hours, unit="hours", period="current as of retrieval", kind="policy",
        method="Read from the 'How performance is measured' text of the city's Pothole Response scorecard page.",
        confidence="provisional",
        caveats="The same page defines the monthly figure as requests responded to 'within three business days' divided by requests received, "
                "which is not identical to 72 hours. The page text holds no measured percentage; the values sit in an embedded dashboard "
                "backed by the Scorecards dataset, which has not been retrieved."))

    # ---- Survey frequency statements (method facts that disagree) --------------------------
    prop = arc("sfcta-prop-l-resurfacing-5ypp-2023")
    prop.require(r"SFPW inspects each of the City's blocks and assigns a Pavement Condition Index \(PCI\) score every two years", "Public Works inspection interval")
    claims.append(base(
        "sfcta-prop-l-resurfacing-5ypp-2023", id="sf-publicworks-pci-interval-years",
        statement="The Prop L program document says San Francisco Public Works inspects each block and assigns a PCI score every two years.",
        value=2, unit="years", period="as stated July 2023", kind="policy",
        method="Read from the Project Information Form text in the Prop L 5-Year Prioritization Program (approved 2023-07-25).",
        confidence="provisional",
        caveats="Conflicts with the MTC statement of a three-year survey update and the city scorecard's annual publication. "
                "Unresolved; Assess should not choose between them."))
    mtc_prog = arc("mtc-pci-program-page")
    mtc_prog.require(r"data set, which includes pavement conditions and maintenance history records, is updated every three years", "MTC survey interval")
    claims.append(base(
        "mtc-pci-program-page", id="mtc-pavement-survey-update-interval-years",
        statement="MTC says its pavement conditions data set, built from local pavement distress surveys, is updated every three years.",
        value=3, unit="years", period="current as of retrieval", kind="policy",
        method="Read from the MTC Pavement Conditions Index program page text.",
        confidence="provisional",
        caveats="Regional program statement, not specific to San Francisco. Conflicts with the Public Works statement of a two-year inspection cycle."))
    return claims


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    args = ap.parse_args(argv)
    try:
        claims = build(args.root)
    except ExtractError as exc:
        print(f"EXTRACT FAILED, nothing written: {exc}")
        return 1
    out = Path(args.root) / "cities" / SLUG / "claims.yaml"
    prior = {c["id"]: c for c in validate.load_yaml(out)} if out.exists() else {}
    for c in claims:
        if c["id"] in prior:
            c["confidence"] = prior[c["id"]]["confidence"]
    out.write_text(HEADER + yaml.safe_dump(claims, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8")
    errors = validate.validate_file(out, "claims.schema.json")
    for line in errors:
        print("SCHEMA", line)
    for c in claims:
        print(f"{c['id']:48} {c['value']!s:>10} {c['unit']}")
    print(f"{len(claims)} claims written")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
